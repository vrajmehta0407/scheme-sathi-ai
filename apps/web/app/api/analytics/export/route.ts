import { NextRequest, NextResponse } from 'next/server';
import { computeAnalyticsOverview } from '@/lib/analytics';

export async function GET(req: NextRequest) {
  const { searchParams } = new URL(req.url);
  const overview = computeAnalyticsOverview({
    state: searchParams.get('state') ?? undefined,
    category: searchParams.get('category') ?? undefined,
    occupation: searchParams.get('occupation') ?? undefined,
    incomeBand: searchParams.get('incomeBand') ?? undefined,
  });

  const header =
    'State,Households_Synthetic,Eligible_Households,Docs_Ready_Households,Eligibility_Rate_Pct,Coverage_Gap_Pct,Unclaimed_Benefit_Rs,Suppressed_Under_30\n';
  const rows = overview.byState
    .map(
      (s) =>
        `"${s.state}",${s.households},${s.eligibleHouseholds},${s.docsReadyHouseholds},${s.eligibilityRatePct},${s.coverageGapPct},${s.unclaimedBenefitRs},${s.suppressed}`
    )
    .join('\n');

  const csv = `# Synthetic data generated by Scheme Sathi AI (n=${overview.sampleSize})\n` + header + rows;

  return new NextResponse(csv, {
    status: 200,
    headers: {
      'Content-Type': 'text/csv; charset=utf-8',
      'Content-Disposition': 'attachment; filename="scheme-sathi-synthetic-analytics.csv"',
    },
  });
}

